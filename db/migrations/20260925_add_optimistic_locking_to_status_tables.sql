    ADD COLUMN IF NOT EXISTS version INT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

